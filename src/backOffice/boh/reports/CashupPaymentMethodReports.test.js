import fs from "fs";
import path from "path";
import { buildCurrencyTotals, buildPaymentMethodTotals, nullableMoney, nullableNumber } from "./ShiftReportModal";

const read = (relativePath) => fs.readFileSync(path.resolve(__dirname, relativePath), "utf8");

describe("cashup reports include cash and non-cash payment methods", () => {
  test("open shift counted amounts remain pending through detail and aggregation", () => {
    const rows = [{
      shift_id: "shift-1",
      payment_name: "Cash",
      money_code: "cash",
      currency_code: "USD",
      payment_count: 2,
      expected_amount: nullableNumber(20),
      counted_amount: nullableNumber(null),
      variance: nullableNumber(null),
    }];

    const totals = buildPaymentMethodTotals(rows);

    expect(totals[0]).toMatchObject({
      shift_count: 1,
      payment_count: 2,
      expected_amount: 20,
      counted_amount: null,
      variance: null,
    });
    expect(nullableMoney(totals[0].counted_amount, "USD")).toBe("Pending");
    expect(nullableMoney(0, "USD")).toBe("USD 0.00");
  });

  test("open shift currency totals remain pending instead of becoming zero", () => {
    const totals = buildCurrencyTotals([
      { currency_code: "USD", payment_count: 2, expected_amount: 20, counted_amount: null, variance: null },
      { currency_code: "USD", payment_count: 1, expected_amount: 10, counted_amount: 10, variance: 0 },
    ]);

    expect(totals[0]).toMatchObject({
      currency_code: "USD",
      shifts: 2,
      payments: 3,
      expected: 30,
      counted: null,
      variance: null,
    });
  });

  test("hospitality cashup workspace renders every saved tender", () => {
    const source = read("../../pages/report/PosReportsModal.js");

    expect(source).toContain("All Payment Methods (Cash and Non-Cash)");
    expect(source).toContain('payment.payment_name || "Payment"');
    expect(source).toContain('payment.money_code || ""');
    expect(source).toContain('currencyAmount(entry, currencyCode, "expected_amount")');
    expect(source).toContain('currencyAmount(entry, currencyCode, "counted_amount")');
    expect(source).toContain('["Payment Method", "Money Code", "Currency", "Payments"]');
    expect(source).toContain("Account Credit Activity (Not Received Tender)");
    expect(source).toContain("row.cashup_bracket_date || row.trading_date");
  });

  test("Hospitality shift report is fixed to the hospitality mode and exposes till and tender detail", () => {
    const source = read("ShiftReportModal.js");
    const adminLayout = read("../../AdminLayOut.js");

    expect(source).toContain("row.cashup_payment_summary || row.payment_summary");
    expect(source).toContain('title="Payment Method Summary"');
    expect(source).toContain('title="Shift Payment Method Detail"');
    expect(source).toContain("Cash and every non-cash tender");
    expect(source).toContain('business_mode: "fast_food_boh"');
    expect(source).toContain('businessModeLabel="Hospitality"');
    expect(source).toContain('periodLabel="Trading Date Period"');
    expect(source).not.toMatch(/retail/i);
    expect(source).toContain('const till = `${r.till_code || ""} ${r.till_name || ""}`');
    expect(source).toContain('title="Account Credit Activity"');
    expect(adminLayout).toContain('businessMode="fast_food_boh"');
    expect(adminLayout).not.toContain('businessMode={isHospitality ? "fast_food_boh" : "retail"}');
  });

  test("cashup history exposes method summary and cashup-level tender detail", () => {
    const source = read("CashupHistoryReportModal.js");

    expect(source).toContain("toArray(row.payment_summary)");
    expect(source).toContain('title="Payment Method Summary"');
    expect(source).toContain('title="Cashup Payment Method Detail"');
    expect(source).toContain('title="Account Credit Activity"');
    expect(source).not.toContain("supported={{ till_id: false }}");
  });

  test("Hospitality cash movement filters initialise from the authoritative trading date", () => {
    const source = read("CashoutReportModal.js");

    expect(source).toContain("getCurrentTradingDay");
    expect(source).toContain("withAuthoritativeTradingDate");
    expect(source).toContain("onFilterChange={refreshBranchTradingDate}");
    expect(source).not.toContain("supported={{ till_id: false }}");
  });

  test("cashup history and shift downloads are generated by backend endpoints", () => {
    const service = read("../../../services/CashupReportsService.js");

    expect(service).toContain('"/api/pos/cashups/export/excel"');
    expect(service).toContain('"/api/pos/cashups/export/pdf"');
    expect(service).toContain('"/api/pos/shift-compliance/report/export/excel"');
    expect(service).toContain('"/api/pos/shift-compliance/report/export/pdf"');
  });
});
